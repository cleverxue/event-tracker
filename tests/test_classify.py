def main() -> int:
    failed = 0
    for title, fam, stage in CASES:
        got = classify_announcement(title)
        if got != (fam, stage):
            failed += 1
            print(f"[FAIL] {title[:44]}\n       期望 {(fam, stage)}，实际 {got}")
    print(f"分类测试: {len(CASES) - failed}/{len(CASES)} 通过")

    p_failed = 0
    for title, body, ptype, expect in PRICE_CASES:
        got = extract_price(title, body)
        if got.price_type != ptype:
            p_failed += 1
            print(f"[FAIL] {body[:40]} 期望 {ptype}，实际 {got.price_type}")
            continue
        if ptype == "range":
            ok = (got.price_low, got.price_high) == expect
        elif ptype in ("fixed", "ceiling"):
            ok = (got.price_fixed if ptype == "fixed" else got.price_high) == expect
        else:
            ok = True
        if not ok:
            p_failed += 1
            print(f"[FAIL] {body[:40]} 值不符: {got}")
    print(f"价格测试: {len(PRICE_CASES) - p_failed}/{len(PRICE_CASES)} 通过")

    # 繁简归一抽查
    assert normalize_text("不高於人民幣120元╱股") == "不高于人民币120元/股"
    print("繁简归一: 通过")

    # 进展公告累计量抽取
    g_failed = 0
    for body, expect in PROGRESS_CASES:
        got = extract_progress(body)
        if got != expect:
            g_failed += 1
            print(f"[FAIL] {body[:40]} 期望 {expect}，实际 {got}")
    print(f"进展抽取测试: {len(PROGRESS_CASES) - g_failed}/{len(PROGRESS_CASES)} 通过")

    # A 股代码判定
    s_failed = 0
    for code, expect in SYMBOL_CASES:
        if is_a_share_symbol(code) != expect:
            s_failed += 1
            print(f"[FAIL] is_a_share_symbol({code!r}) 期望 {expect}")
    print(f"代码判定: {len(SYMBOL_CASES) - s_failed}/{len(SYMBOL_CASES)} 通过")

    return 1 if (failed or p_failed or s_failed or g_failed) else 0


if __name__ == "__main__":
    sys.exit(main())
